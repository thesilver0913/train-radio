'use strict';
// 駅リスト(id = pos)。80ch(南北線)は8〜27、81ch(東西線)は40〜59。
const LIST = [
  [8,'湊川桜宮'],[9,'磯上公園'],[10,'東元町'],[11,'新開地'],[12,'春日道'],[13,'江守川'],[14,'水神'],[15,'寺坂'],
  [16,'笹久保公園'],[17,'桂'],[18,'南桂'],[19,'東山公園'],[20,'新淡路'],[21,'国学院前'],[22,'山雲寺'],[23,'桃川台'],
  [24,'伯方南駅'],[25,'四州千代田'],[26,'新如月'],[27,'南伯方学園都市'],
  [40,'伯方港'],[41,'神宮前'],[42,'七番町'],[43,'賀喜西口'],[44,'東海新道'],[45,'ドーム前'],[46,'水神'],[47,'寺坂'],
  [48,'桜ノ道'],[49,'上汐利'],[50,'浦代新町'],[51,'西桂山手'],[52,'夢野町'],[53,'平野'],[54,'西野山公園'],[55,'南区役所'],
  [56,'一乗葉山公園'],[57,'伯方西駅'],[58,'西駅西口'],[59,'東山丘陵'],
];
const BY_ID = new Map(LIST);
const RANGE = { 80: [8, 27], 81: [40, 59] };

// 区間表示。奇数列番=下り(posが増える方向)、偶数列番=上り(posが減る方向)。
// 例: 6110・pos11.5 → "[春日道]→[新開地] 間"。リスト外のposは null(位置不明)。
function section(ch, trainNo, pos) {
  const r = RANGE[ch];
  if (!r || pos == null || !Number.isFinite(pos) || pos < r[0] || pos > r[1]) return null;
  const lo = Math.floor(pos + 1e-9), frac = pos - lo;
  if (frac < 1e-6) { const n = BY_ID.get(lo); return n ? `[${n}]` : null; }
  const hi = lo + 1, a = BY_ID.get(lo), b = BY_ID.get(hi);
  if (!a || !b || hi > r[1]) return null;
  return parseInt(trainNo, 10) % 2 === 0 ? `[${b}]→[${a}] 間` : `[${a}]→[${b}] 間`;
}
module.exports = { section, RANGE };
